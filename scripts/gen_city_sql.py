def main():
    cities = {}
    for line in io.open(os.path.join(DATA_DIR, "cities.tsv"), encoding="utf-8").read().splitlines():
        if line.strip():
            p = line.split("\t")
            cities[int(p[0])] = p[2]

    lines = [
        "-- ============================================================",
        "-- 城市数据扩充：新增 特色美食/乡土人情 列，重写 66 城市介绍与封面图",
        "-- 仅需执行一次",
        "-- ============================================================",
        "ALTER TABLE cities ADD COLUMN specialty_food TEXT COMMENT '特色美食' AFTER description;",
        "ALTER TABLE cities ADD COLUMN local_culture TEXT COMMENT '乡土人情' AFTER specialty_food;",
        "",
    ]
    for cid in sorted(CITY):
        c = CITY[cid]
        name = cities.get(cid, "")
        url = "/images/%s/city.jpg" % sanitize(name)
        lines.append(
            "UPDATE cities SET description='%s', specialty_food='%s', local_culture='%s', image_url='%s' WHERE id=%d;"
            % (esc(c["desc"]), esc(c["food"]), esc(c["culture"]), url, cid)
        )
    lines.append("")

    with io.open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("written %s, %d cities" % (OUT, len(CITY)))


if __name__ == "__main__":
    main()
