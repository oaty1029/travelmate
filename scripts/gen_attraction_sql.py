def sanitize(name):
    name = (name or "").strip()
    return re.sub(r"[\s/\\:*?\"<>|]+", "", name) or "unnamed"


def esc(s):
    return (s or "").replace("\\", "\\\\").replace("'", "''")


def urls_json(city_name, attr_name):
    base = sanitize(attr_name)
    arr = ["/images/%s/attractions/%s_%d.jpg" % (sanitize(city_name), base, i) for i in (1, 2, 3)]
    return json.dumps(arr, ensure_ascii=False)


