def main():
    cities = {}
    for line in io.open(os.path.join(DATA_DIR, "cities.tsv"), encoding="utf-8").read().splitlines():
        if line.strip():
            p = line.split("\t")
            cities[int(p[0])] = p[2]

    attrs = [l.split("\t") for l in io.open(os.path.join(DATA_DIR, "attractions.tsv"), encoding="utf-8").read().splitlines() if l.strip()]

    # 校验 ATTR 覆盖全部现有景点（按名字匹配）
    names = set()
    for a in attrs:
        names.add(a[2])
    missing = [n for n in names if n not in ATTR]
    extra = [n for n in ATTR if n not in names]
    if missing:
        print("WARNING missing descriptions for %d attractions:" % len(missing), missing)
    if extra:
        print("WARNING extra keys in ATTR (not in data):", extra)

    lines = [
        "-- ============================================================",
        "-- 景点数据扩充：重写 248 景点介绍 + 修正 18 条其他分类 + 填 image_urls",
        "-- 并为石家庄/太原/南昌/合肥/珠海各新增 5 个景点",
        "-- 仅需执行一次",
        "-- ============================================================",
        "",
    ]

    # 现有景点 UPDATE
    for a in attrs:
        aid, cid, name, category = int(a[0]), int(a[1]), a[2], a[3]
        cname = cities.get(cid, "城市")
        entry = ATTR.get(name)
        if not entry:
            continue
        new_cat = entry.get("category", category)
        desc = entry["desc"]
        img = urls_json(cname, name)
        lines.append(
            "UPDATE attractions SET description='%s', category='%s', image_urls='%s' WHERE id=%d;"
            % (esc(desc), esc(new_cat), esc(img), aid)
        )
    lines.append("")

    # 新增景点 INSERT
    for n in NEW_ATTRACTIONS:
        cid = None
        for k, v in cities.items():
            if v == n["city"]:
                cid = k
                break
        if cid is None:
            print("WARNING city not found:", n["city"])
            continue
        img = urls_json(n["city"], n["name"])
        lines.append(
            "INSERT INTO attractions (city_id, name, category, description, rating, ticket_price, suggest_duration, open_time, best_season, address, image_urls, status) VALUES "
            "(%d, '%s', '%s', '%s', %s, %s, %d, '%s', '%s', '%s', '%s', 1);"
            % (cid, esc(n["name"]), esc(n["category"]), esc(n["desc"]), n["rating"],
               n["price"], n["dur"], esc(n["open"]), esc(n["season"]), esc(n["address"]), img)
        )
    lines.append("")

    with io.open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("written %s: %d updates + %d inserts" % (OUT, len(attrs), len(NEW_ATTRACTIONS)))


if __name__ == "__main__":
    main()
